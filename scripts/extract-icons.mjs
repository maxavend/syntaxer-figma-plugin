// Renders the official Figma icons FigUI3 doesn't ship (from @create-figma-plugin/ui)
// to SVG strings once, and writes them to ui/icons.js.
// Run with: npm run icons
import { writeFileSync } from 'node:fs';
import { IconDragHandle16 } from '../node_modules/@create-figma-plugin/ui/lib/icons/icon-16/icon-drag-handle-16.js';

const ICONS = {
  dragHandle: IconDragHandle16,
};

function toAttrName(name) {
  return name === 'className' ? 'class' : name;
}

function escapeAttr(value) {
  return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

// Minimal Preact VNode -> string serializer (icons are static <svg>/<path> trees)
function render(vnode) {
  if (vnode == null || vnode === false) return '';
  if (typeof vnode === 'string' || typeof vnode === 'number') return String(vnode);
  if (Array.isArray(vnode)) return vnode.map(render).join('');
  if (typeof vnode.type === 'function') return render(vnode.type(vnode.props));
  const { children, ...attrs } = vnode.props;
  const attrString = Object.entries(attrs)
    .filter(([key, value]) => value != null && key !== 'style')
    .map(([key, value]) => ` ${toAttrName(key)}="${escapeAttr(value)}"`)
    .join('');
  return `<${vnode.type}${attrString}>${render(children)}</${vnode.type}>`;
}

// createIcon() wraps the <svg> in a <div>; keep only the <svg>
function extractSvg(Icon) {
  const wrapper = Icon({});
  const svg = [].concat(wrapper.props.children).find((child) => child && child.type === 'svg');
  return render(svg).replace(/\s+xmlns="[^"]+"/, ' xmlns="http://www.w3.org/2000/svg" aria-hidden="true"');
}

const lines = Object.entries(ICONS).map(
  ([name, Icon]) => `export const ${name} = ${JSON.stringify(extractSvg(Icon))};`,
);

writeFileSync(
  new URL('../ui/icons.js', import.meta.url),
  `// Generated by scripts/extract-icons.mjs from @create-figma-plugin/ui. Do not edit.\n${lines.join('\n')}\n`,
);
console.log(`Wrote ${lines.length} icons to ui/icons.js`);
